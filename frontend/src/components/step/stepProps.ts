import type { RenderedNode, TraversalAction } from '../../api/types'

/**
 * props ที่กล่องขั้นตอนทุกแบบรับเหมือนกัน
 *
 * กล่องขั้นตอนไม่เรียก API เอง รับสถานะปัจจุบันเข้ามา แล้วแจ้งออกว่าผู้ใช้
 * ต้องการทำอะไรผ่าน onAction เท่านั้น การตัดสินว่าจะไปสถานะไหนต่อเป็นหน้าที่
 * ของกลไกควบคุมเครื่องสถานะฝั่งเซิร์ฟเวอร์ ไม่ใช่ของหน้าจอ
 *
 * ผลดี: แสดงในหน้า gallery และเขียนเทสได้โดยไม่ต้องมีเซิร์ฟเวอร์
 * (หลักเดียวกับที่กลไกควบคุมเครื่องสถานะไม่ import NestJS)
 *
 * ศัพท์: `RenderedNode` = สถานะที่จัดรูปพร้อมแสดงแล้ว, `nodeId` = รหัสของสถานะ
 */
export interface StepProps {
  /** สถานะปัจจุบันที่เซิร์ฟเวอร์ส่งมา */
  node: RenderedNode
  /** แจ้งการกระทำของผู้ใช้ออกไป ผู้เรียกเป็นคนส่งต่อให้เซิร์ฟเวอร์ */
  onAction: (action: TraversalAction) => void
  /** true = กำลังรอเซิร์ฟเวอร์ตอบ กล่องต้องปิดทุกปุ่ม กันส่งซ้ำ */
  isPending: boolean
  /** เช่น 'Samsung AR70H**D1***' หน้าตรวจอาการหาได้จาก GraphSummary */
  manualLabel?: string
}