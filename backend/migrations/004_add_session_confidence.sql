-- เพิ่มคะแนนความมั่นใจของ session (ขั้น 1.8)
--
-- ความหมาย: คะแนนความคล้าย (cosine) ระหว่างคำค้นของผู้ใช้กับผังขั้นตอนที่เลือก
--           เซิร์ฟเวอร์คำนวณเองตอนเริ่ม session ไม่รับค่านี้จากหน้าเว็บ
--           ไม่ใช่ความน่าจะเป็น และไม่มีผลต่อการเปลี่ยนสถานะใดๆ (แสดงผลอย่างเดียว)
--
-- NULL = ไม่มีการจับคู่ให้วัด เช่น ผู้ใช้เลือกอาการจากรายการเอง หรือระบบค้นหายังไม่พร้อม
--        ห้ามใช้ 0 หรือ 1 แทน เพราะจะปนกับ "คะแนนต่ำจริง" / "ตรงเป๊ะจริง"
--
-- เพิ่มคอลัมน์ที่ยอมให้เป็น NULL เท่านั้น: แถวเดิมได้ NULL อัตโนมัติ
-- ไม่ต้องแก้ข้อมูลเก่า และโค้ดรุ่นก่อนหน้ายังอ่านตารางนี้ได้ (คอลัมน์ที่ไม่รู้จักถูกข้าม)
--
-- DECIMAL(4,3) = ทศนิยม 3 ตำแหน่ง ตรงกับที่ API ปัดเศษ (เช่น 0.707)
-- ไม่ใช้ IF NOT EXISTS เพราะ MySQL ไม่รองรับกับ ADD COLUMN
-- ตัวรัน migration จำไฟล์ที่รันแล้วอยู่แล้ว จึงไม่รันซ้ำ

ALTER TABLE sessions
  ADD COLUMN confidence DECIMAL(4,3) NULL
  COMMENT 'คะแนนความคล้าย (cosine) ของผังที่เลือก NULL = ไม่มีการจับคู่ให้วัด'
  AFTER variables;