-- backend/migrations/005_add_session_outcome.sql
--
-- เพิ่มช่องเก็บ "ผลลัพธ์ที่ผู้ใช้กรอก" ตอนการตรวจจบแล้ว (หน้าสถานะสิ้นสุด)
--
-- ความหมาย: ข้อความอิสระที่ผู้ใช้เขียนเองว่าทำตามขั้นตอนแล้วผลเป็นอย่างไร
--           เช่น "ทำตามแล้วแอร์กลับมาทำงานปกติ" หรือ "ยังไม่หาย"
--
-- เป็นข้อมูลบันทึกอย่างเดียว (เหมือน confidence ใน 004):
--   - กลไกควบคุมเครื่องสถานะไม่อ่านค่านี้ ไม่ใช้ตัดสินขั้นถัดไปหรือด่านความปลอดภัย
--   - ไม่ใช้ในระบบค้นหาอาการ และไม่ใช้คำนวณความแม่นยำของอะไรทั้งสิ้น
--
-- NULL = ผู้ใช้ยังไม่ได้กรอก (การกรอกไม่บังคับ ผู้ใช้เริ่มตรวจใหม่ได้โดยไม่กรอก)
--        ห้ามใช้สตริงว่างแทน NULL เพราะแยกไม่ออกระหว่าง "ยังไม่กรอก" กับ "กรอกว่าง"
--        (ตัวตรวจ body ฝั่ง API ไม่ให้เก็บข้อความว่างอยู่แล้ว)
--
-- outcome_text   TEXT: ความยาวสูงสุดที่ API รับถูกจำกัดที่ฝั่งแอป (ค่าที่เสนอ 1,000 ตัวอักษร)
--                ตัวอักษร 1 ตัวใน utf8mb4 ใช้สูงสุด 4 ไบต์ (ภาษาไทยใช้ 3 ไบต์ อีโมจิใช้ 4 ไบต์)
--                1,000 ตัวอักษรจึงไม่เกิน 4,000 ไบต์ ต่ำกว่าขีดจำกัด 65,535 ไบต์ของ TEXT มาก
--                ตารางนี้เป็น utf8mb4 อยู่แล้ว คอลัมน์ใหม่สืบทอดชุดอักขระมาเอง
-- outcome_at     DATETIME: เวลาที่บันทึกข้อความ ตั้งด้วย NOW() ใน SQL ตามข้อตกลงของ SessionStore
--                (ไม่ใช้เวลาจาก JavaScript) ใช้ DATETIME ตามที่ตกลงไว้ ต่างจาก created_at/expires_at
--                ที่เป็น TIMESTAMP ตรงที่ DATETIME ไม่แปลงตาม time zone ตอนอ่าน
--                ค่านี้ไม่ถูกเอาไปเทียบกับคอลัมน์เวลาอื่น จึงไม่มีผลต่อการหมดอายุของ session
--
-- ข้อควรรู้ด้านข้อมูล:
--   - ข้อความเป็นข้อความอิสระ ผู้ใช้อาจพิมพ์ข้อมูลส่วนตัวมาเอง หน้าจอจึงมีคำเตือนไม่ให้ใส่
--   - ยังไม่มีตัวกวาดแถวที่หมดอายุ (ดูคอมเมนต์ใน session.store.ts) ข้อความจึงอยู่ในตารางต่อไป
--     แม้ session หมดอายุจนอ่านผ่าน API ไม่ได้แล้ว
--   - ตาราง sessions มี updated_at แบบ ON UPDATE CURRENT_TIMESTAMP การบันทึกข้อความจึงทำให้
--     updated_at เปลี่ยนตามไปด้วย (ไม่มีผลต่อ expires_at)
--
-- เพิ่มคอลัมน์ที่ยอมให้เป็น NULL เท่านั้น ไม่แก้และไม่ลบของเดิม:
--   แถวเดิมได้ NULL อัตโนมัติ ไม่ต้องแก้ข้อมูลเก่า
--   และ backend รุ่นก่อนหน้าที่ยังรันอยู่ (เช่นบน Render ระหว่างรอ deploy) ยังอ่านและเขียนตารางนี้ได้
--   เพราะ SQL ของมันระบุชื่อคอลัมน์ที่ใช้เองทั้งหมด ไม่ได้ใช้ SELECT * หรือ INSERT โดยไม่ระบุคอลัมน์
--   ด้วยเหตุนี้ลำดับการขึ้นระบบคือ "รัน migration นี้ก่อน แล้วค่อย deploy โค้ดใหม่" ไม่ใช่กลับกัน
--   (โค้ดใหม่ที่ SELECT คอลัมน์นี้จะพังถ้าฐานข้อมูลยังไม่มีคอลัมน์)
--
-- ใช้ ALTER TABLE คำสั่งเดียวเพิ่มสองคอลัมน์ เพราะตัวรัน migration ไม่ครอบ transaction
-- และ MySQL 8 ทำ DDL แบบ atomic ต่อ 1 คำสั่ง จึงไม่มีสถานะที่ได้คอลัมน์เดียว
-- ไม่ใช้ IF NOT EXISTS เพราะ MySQL ไม่รองรับกับ ADD COLUMN
-- ตัวรัน migration จำไฟล์ที่รันแล้วอยู่แล้ว จึงไม่รันซ้ำ

ALTER TABLE sessions
  ADD COLUMN outcome_text TEXT NULL
  COMMENT 'ข้อความผลลัพธ์ที่ผู้ใช้กรอกตอนการตรวจจบ NULL = ยังไม่ได้กรอก (บันทึกอย่างเดียว ไม่มีผลต่อการเปลี่ยนสถานะ)'
  AFTER confidence,
  ADD COLUMN outcome_at DATETIME NULL
  COMMENT 'เวลาที่บันทึก outcome_text (NOW() ใน SQL) NULL = ยังไม่ได้กรอก'
  AFTER outcome_text;
